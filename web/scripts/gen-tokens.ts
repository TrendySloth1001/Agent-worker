import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export type NumberMap = Record<string, number>;
export type Palette = Record<string, string>;

const HEADER = "/* generated by scripts/gen-tokens.ts */";

const LINE_HEIGHTS: Record<string, number> = {
  caption: 1.3,
  label: 1.3,
  "body-small": 1.45,
  body: 1.5,
  title: 1.3,
  metric: 1.15,
  headline: 1.1,
  display: 1,
  "display-large": 1,
};

const EASINGS: Record<string, string> = {
  standard: "cubic-bezier(0.2, 0, 0, 1)",
  emphasized: "cubic-bezier(0.05, 0.7, 0.1, 1)",
  exit: "cubic-bezier(0.3, 0, 0.8, 0.15)",
};

const DERIVED: Record<string, readonly [light: string, dark: string]> = {
  cell: ["surface", "surface-raised"],
  "cell-high": ["surface-high", "border"],
  field: ["surface-raised", "surface-high"],
};

const COMPONENT_SIZES = [
  "buttonHeight",
  "inputHeight",
  "rowHeight",
  "minTap",
  "toggleWidth",
  "toggleHeight",
  "toggleKnob",
  "sheetHandleWidth",
  "chipHeight",
  "segmentHeight",
  "dotGridSpacing",
  "dotGridRadius",
  "statusDot",
] as const;

const SETTINGS_SIZES = ["iconCircle", "iconGlyph", "avatar", "groupGap", "touchTarget"] as const;

export const kebab = (name: string): string =>
  name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const classBody = (src: string, className: string): string => {
  const start = src.search(new RegExp(`class\\s+${className}\\b`));
  if (start < 0) throw new Error(`class ${className} not found`);
  const end = src.indexOf("\n}", start);
  return src.slice(start, end < 0 ? undefined : end);
};

export const toCssColor = (argb: string): string => {
  const hex = argb.replace(/^0x/i, "").toLowerCase().padStart(8, "0");
  const alpha = hex.slice(0, 2);
  const rgb = hex.slice(2);
  return alpha === "ff" ? `#${rgb}` : `#${rgb}${alpha}`;
};

export const parseColors = (src: string): Palette => {
  const colors: Palette = {};
  for (const m of src.matchAll(/static const (\w+) = Color\(0x([0-9a-fA-F]{8})\);/g)) {
    const [, name, value] = m;
    if (name && value) colors[name] = toCssColor(value);
  }
  for (const m of src.matchAll(/static const (\w+) = (\w+);/g)) {
    const [, name, target] = m;
    const value = target ? colors[target] : undefined;
    if (name && value) colors[name] = value;
  }
  return colors;
};

export const parsePaletteRoles = (
  src: string,
  variant: "dark" | "light",
  colors: Palette,
): Palette => {
  const start = src.search(new RegExp(`static const ${variant} = AppPalette\\(`));
  if (start < 0) throw new Error(`palette ${variant} not found`);
  const body = src.slice(start, src.indexOf(");", start));
  const roles: Palette = {};
  for (const m of body.matchAll(/^\s*(\w+): AppColors\.(\w+),/gm)) {
    const [, role, colorName] = m;
    if (!role || !colorName) continue;
    const css = colors[colorName];
    if (!css) throw new Error(`unknown color ${colorName}`);
    roles[kebab(role)] = css;
  }
  return roles;
};

export const parseNumbers = (src: string, className: string): NumberMap => {
  const out: NumberMap = {};
  const body = classBody(src, className);
  for (const m of body.matchAll(/static const (\w+) = (-?[\d.]+);/g)) {
    const [, name, value] = m;
    if (name && value) out[name] = Number(value);
  }
  for (const m of body.matchAll(/static const (\w+) = Duration\(milliseconds: (\d+)\)/g)) {
    const [, name, value] = m;
    if (name && value) out[name] = Number(value);
  }
  return out;
};

const pick = (map: NumberMap, keys: readonly string[]): NumberMap =>
  Object.fromEntries(
    keys.map((key) => {
      const value = map[key];
      if (value === undefined) throw new Error(`missing ${key}`);
      return [key, value];
    }),
  );

const px = (value: number): string => `${value}px`;

const block = (selector: string, lines: string[], indent = ""): string =>
  `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join("\n")}\n${indent}}`;

const colorVars = (roles: Palette): string[] =>
  Object.entries(roles).map(([role, value]) => `--${role}: ${value};`);

export interface TokenInput {
  light: Palette;
  dark: Palette;
  darkAccentText: string;
  spacing: NumberMap;
  radius: NumberMap;
  fontSize: NumberMap;
  border: NumberMap;
  sizes: NumberMap;
  settings: NumberMap;
  durations: NumberMap;
}

export const buildTokens = (t: TokenInput): string => {
  const sizes = { ...pick(t.sizes, COMPONENT_SIZES), ...pick(t.settings, SETTINGS_SIZES) };
  const radii: NumberMap = {
    ...t.radius,
    card: t.radius["dialog"] ?? 28,
    "group-outer": t.settings["groupOuterRadius"] ?? 28,
    "group-inner": t.settings["groupInnerRadius"] ?? 6,
  };

  const derive = (palette: Palette, index: 0 | 1): Palette =>
    Object.fromEntries(
      Object.entries(DERIVED).map(([name, refs]) => [name, palette[refs[index]] ?? ""]),
    );
  const light = { ...t.light, ...derive(t.light, 0), "accent-text": t.light["accent"] ?? "" };
  const dark = { ...t.dark, ...derive(t.dark, 1), "accent-text": t.darkAccentText };

  const themeLines = [
    ...Object.keys(light).map((r) => `--color-${r}: var(--${r});`),
    ...Object.entries(t.spacing).map(([k, v]) => `--spacing-${kebab(k)}: ${px(v)};`),
    ...Object.entries(sizes).map(([k, v]) => `--spacing-${kebab(k)}: ${px(v)};`),
    ...Object.entries(radii).map(([k, v]) => `--radius-${kebab(k)}: ${px(v)};`),
    ...Object.entries(t.fontSize).flatMap(([k, v]) => {
      const name = kebab(k);
      const lh = LINE_HEIGHTS[name];
      const lines = [`--text-${name}: ${px(v)};`];
      if (lh !== undefined) lines.push(`--text-${name}--line-height: ${lh};`);
      return lines;
    }),
    ...Object.entries(EASINGS).map(([k, v]) => `--ease-${k}: ${v};`),
  ];
  const durationLines = Object.entries(t.durations)
    .filter(([k]) => ["fast", "normal", "slow"].includes(k))
    .map(([k, v]) => `--duration-${k}: ${v}ms;`);
  const borderLines = Object.entries(t.border).map(([k, v]) => `--border-${kebab(k)}: ${px(v)};`);

  const darkBlock = block('[data-theme="dark"]', ["color-scheme: dark;", ...colorVars(dark)]);
  const darkMedia = [
    "@media (prefers-color-scheme: dark) {",
    block(':root:not([data-theme="light"])', ["color-scheme: dark;", ...colorVars(dark)], "  "),
    "}",
  ].join("\n");

  return [
    HEADER,
    block(":root", ["color-scheme: light;", ...colorVars(light), ...borderLines]),
    darkBlock,
    darkMedia,
    block(
      "@theme inline",
      themeLines.filter((l) => l.startsWith("--color-")),
    ),
    block("@theme", [...themeLines.filter((l) => !l.startsWith("--color-")), ...durationLines]),
    "",
  ].join("\n\n");
};

const read = (root: string, rel: string): string => readFileSync(resolve(root, rel), "utf8");

export const generate = (root: string): string => {
  const colorsSrc = read(root, "frontend/lib/core/constants/app_colors.dart");
  const sizesSrc = read(root, "frontend/lib/core/constants/app_sizes.dart");
  const settingsSrc = read(root, "frontend/lib/core/constants/settings_copy.dart");
  const paletteSrc = read(root, "frontend/lib/core/theme/app_palette.dart");

  const colors = parseColors(colorsSrc);

  return buildTokens({
    light: parsePaletteRoles(paletteSrc, "light", colors),
    dark: parsePaletteRoles(paletteSrc, "dark", colors),
    darkAccentText: colors["snackAccentOnDark"] ?? "#ff6b6b",
    spacing: parseNumbers(sizesSrc, "AppSpacing"),
    radius: parseNumbers(sizesSrc, "AppRadius"),
    fontSize: parseNumbers(sizesSrc, "AppFontSize"),
    border: parseNumbers(sizesSrc, "AppBorder"),
    sizes: parseNumbers(sizesSrc, "AppSizes"),
    settings: parseNumbers(settingsSrc, "SettingsSizes"),
    durations: parseNumbers(sizesSrc, "AppDurations"),
  });
};

const isMain = (): boolean => {
  const entry = process.argv[1];
  return entry !== undefined && import.meta.url === pathToFileURL(entry).href;
};

if (isMain()) {
  const here = dirname(fileURLToPath(import.meta.url));
  const css = generate(resolve(here, "../.."));
  writeFileSync(resolve(here, "../src/styles/tokens.css"), css);
}
