import { describe, expect, it } from "vitest";
import {
  buildTokens,
  kebab,
  parseColors,
  parseNumbers,
  parsePaletteRoles,
  toCssColor,
} from "./gen-tokens";

const COLORS = `
abstract final class AppColors {
  static const black = Color(0xFF000000);
  static const red = Color(0xFFD71921);
  static const darkGlass = Color(0xB3141414);
  static const darkBackground = black;
}`;

const PALETTE = `
  static const dark = AppPalette(
    background: AppColors.darkBackground,
    accent: AppColors.red,
    isDark: true,
  );
  static const light = AppPalette(
    background: AppColors.black,
    accent: AppColors.red,
    isDark: false,
  );
`;

const SIZES = `
abstract final class AppSpacing {
  static const sm = 8.0;
  static const lg = 16.0;
}
abstract final class AppDurations {
  static const fast = Duration(milliseconds: 150);
}`;

describe("gen-tokens", () => {
  it("converts ARGB to css", () => {
    expect(toCssColor("0xFFD71921")).toBe("#d71921");
    expect(toCssColor("0xB3141414")).toBe("#141414b3");
  });

  it("parses colors and aliases", () => {
    expect(parseColors(COLORS)).toMatchObject({
      red: "#d71921",
      darkGlass: "#141414b3",
      darkBackground: "#000000",
    });
  });

  it("parses palette roles per variant", () => {
    const colors = parseColors(COLORS);
    expect(parsePaletteRoles(PALETTE, "dark", colors)).toEqual({
      background: "#000000",
      accent: "#d71921",
    });
  });

  it("parses numeric and duration constants", () => {
    expect(parseNumbers(SIZES, "AppSpacing")).toEqual({ sm: 8, lg: 16 });
    expect(parseNumbers(SIZES, "AppDurations")).toEqual({ fast: 150 });
  });

  it("kebab-cases dart names", () => {
    expect(kebab("surfaceRaised")).toBe("surface-raised");
  });

  it("emits themed blocks with the generated header", () => {
    const css = buildTokens({
      light: { background: "#f4f4f2", accent: "#d71921" },
      dark: { background: "#000000", accent: "#d71921" },
      darkAccentText: "#ff6b6b",
      spacing: { sm: 8 },
      radius: { dialog: 28 },
      fontSize: { body: 16 },
      border: { thin: 1 },
      sizes: {
        buttonHeight: 48,
        inputHeight: 52,
        rowHeight: 52,
        minTap: 48,
        toggleWidth: 40,
        toggleHeight: 22,
        toggleKnob: 14,
        sheetHandleWidth: 32,
        chipHeight: 24,
        segmentHeight: 36,
        dotGridSpacing: 18,
        dotGridRadius: 1,
        statusDot: 8,
      },
      settings: { iconCircle: 40, iconGlyph: 22, avatar: 56, groupGap: 2, touchTarget: 56 },
      durations: { fast: 150 },
    });
    expect(css.startsWith("/* generated by scripts/gen-tokens.ts */")).toBe(true);
    expect(css).toContain('[data-theme="dark"]');
    expect(css).toContain(':root:not([data-theme="light"])');
    expect(css).toContain("--color-background: var(--background);");
    expect(css).toContain("--radius-card: 28px;");
  });
});
